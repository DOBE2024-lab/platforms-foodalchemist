// Offline-Abnahme mit der von HandbuchDarstellungTest gerenderten Fixture.
// Playwright/Chrome sind externe Prüfwerkzeuge, keine Produktabhängigkeiten.
const fs=require('fs'),path=require('path'),os=require('os'),assert=require('node:assert/strict');
const {chromium}=require(process.env.FA_PLAYWRIGHT_MODULE || 'playwright');
const root=path.resolve(__dirname,'../..');
const fixture=process.env.FA_HANDBUCH_BAUM_PREVIEW_PATH || path.join(os.tmpdir(),'fa-handbuch-baum-render.html');
const screenshots=process.env.FA_HANDBUCH_SCREENSHOT_DIR || os.tmpdir();
fs.mkdirSync(screenshots,{recursive:true});
assert.ok(fs.existsSync(fixture),'Zuerst HandbuchDarstellungTest mit FA_HANDBUCH_BAUM_PREVIEW_PATH ausführen.');
(async()=>{
 const browser=await chromium.launch({...(process.env.FA_CHROME_EXECUTABLE ? {executablePath:process.env.FA_CHROME_EXECUTABLE} : {channel:'chrome'}),headless:true});
 for(const width of [375,390,768,1280]){
  const page=await browser.newPage({viewport:{width,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',route=>{
   const u=new URL(route.request().url());
   if(u.pathname.endsWith('.css'))return route.fulfill({contentType:'text/css',body:fs.readFileSync(root+'/resources/css/handbuch.css','utf8')});
   if(u.pathname.endsWith('.png'))return route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="640" height="420"><rect width="640" height="420" fill="#8fb0ff"/><text x="40" y="220" font-size="36">Lokales Testbild</text></svg>'});
   return route.fulfill({contentType:'text/html',body:fs.readFileSync(fixture,'utf8')});
  });
  await page.goto('http://handbuch.test/p/handbuch/test');
  assert.equal(await page.locator('nav details[open]').count(),0);
  await page.locator('#handbuch-gaeste').fill('100');
  await page.locator('nav > details > summary').click();
  await page.locator('nav details.konzept > summary').first().click();
  assert.equal(await page.locator('nav a[data-key="r1"]').isVisible(),false);
  await page.locator('nav details.paket > summary').first().click();
  assert.match(await page.locator('nav a[data-key="r1"]').textContent(),/0,33 Teile je Gast/);
  assert.match(await page.locator('nav a[data-key="r1"] [data-menge-pro-gast]').textContent(),/33 Teile/);
  await page.screenshot({path:path.join(screenshots,`fa-handbuch-baum-${width}.png`)});
  await page.locator('nav a[data-key="r1"]').click();
  const dish=page.locator('#g-r1');assert.equal(await dish.locator('.px').inputValue(),'33');
  await dish.locator('.px').fill('10');
  await dish.locator('[data-sub="r1-b2-1"]').click();
  await dish.locator('#sb-r1-b2-1 .vorschau-titel').click();
  const base=page.locator('#g-basis-b2');
  assert.equal(await base.locator('.basis-px').inputValue(),'10');
  assert.equal(await base.locator('.basis-ziel').inputValue(),'0,8');
  await base.locator('.basis-ziel').fill('0,5');
  assert.equal(await base.locator('.basis-px').inputValue(),'6.25');
  assert.equal((await base.locator('td[data-original="800"]').textContent()).trim(),'400 Gramm');
  await base.locator('.basis-ziel-einheit').selectOption('g');
  assert.equal(await base.locator('.basis-ziel').inputValue(),'500');
  await base.locator('.basis-ziel').fill('2000');
  assert.equal(await base.locator('.basis-px').inputValue(),'25');
  assert.equal((await base.locator('[data-bedarf-menge]').textContent()).trim(),'2 kg');
  await base.locator('.basis-ziel').fill('-1');
  assert.equal(await base.locator('[data-basis-ziel-fehler]').isVisible(),true);
  assert.equal((await base.locator('[data-bedarf-menge]').textContent()).trim(),'2 kg');
  await base.locator('.basis-ziel').fill('400');
  await base.locator('.basis-ziel-einheit').selectOption('kg');
  assert.equal(await base.locator('.basis-ziel').inputValue(),'0,4');
  await base.locator('.basis-ziel').fill('0,');
  assert.equal(await base.locator('.basis-ziel').inputValue(),'0,','Komma wird beim Tippen nicht entfernt');
  await base.locator('.basis-ziel').fill('0,4');
  await base.locator('[data-basis-step="1"]').click();
  assert.equal(await base.locator('.basis-px').inputValue(),'6');
  assert.equal(await base.locator('.basis-ziel').inputValue(),'0,48');
  await base.locator('.basis-px').fill('20');
  assert.equal(await base.locator('.basis-ziel').inputValue(),'1,6');
  await page.screenshot({path:path.join(screenshots,`fa-handbuch-rechner-${width}.png`)});
  await base.locator('.original-umschalter').click();
  assert.equal(await base.locator('.basis-ziel').inputValue(),'1');
  await base.locator('.original-umschalter').click();
  assert.equal(await base.locator('.basis-ziel').inputValue(),'1,6');
  if(width<=800)await page.locator('#zurueck').click();else await base.locator('[data-basis-zurueck]').click();
  assert.equal(await dish.locator('.px').inputValue(),'10','Gerichtsportionen bleiben unabhängig');
  if(width<=800)await page.locator('#zurueck').click();
  await page.locator('nav details.paket > summary').nth(1).click();
  await page.locator('nav a[data-key="r3"]').click();
  const other=page.locator('#g-r3');assert.equal(await other.locator('.px').inputValue(),'100');
  await other.locator('.px').fill('2');
  if(width<=800)await page.locator('#zurueck').click();
  await page.locator('#handbuch-gaeste').fill('200');
  await page.locator('nav a[data-key="r1"]').click();
  assert.equal(await dish.locator('.px').inputValue(),'10');
  assert.equal(await other.locator('.px').inputValue(),'2');
  await dish.evaluate(el=>{el.querySelector('#sb-r1-b2-1 .basis-link').dataset.faktor='0';});
  if(width<=800)await page.locator('#zurueck').click();
  await page.locator('nav a[data-key="r1"]').click();
  await dish.locator('#sb-r1-b2-1 .vorschau-titel').click();
  await base.locator('.basis-ziel').fill('1');
  assert.equal(await base.locator('.basis-rechner').isVisible(),false,'Ohne Bedarfsanteil keine erfundene Portionsumrechnung');
  assert.equal(await base.locator('[data-rezeptmodus]').textContent(),'Gewünschte Rezeptmenge');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.goto('http://handbuch.test/p/handbuch/test#basis-b1');
  const standalone=page.locator('#g-basis-b1');
  await standalone.locator('.basis-ziel').fill('0,5');
  assert.equal((await standalone.locator('td[data-original="1000"]').textContent()).trim(),'500 Gramm');
  await standalone.locator('.basis-ziel').fill('0');
  assert.equal((await standalone.locator('td[data-original="1000"]').textContent()).trim(),'0 Gramm');
  await standalone.locator('.original-umschalter').click();
  assert.equal((await standalone.locator('td[data-original="1000"]').textContent()).trim(),'1000 Gramm');
  assert.deepEqual(errors,[]);console.log(JSON.stringify({width,tree:'passed',distribution:'passed',kgAndPortions:'passed',independent:'passed',overflow:false}));
  await page.close();
 }
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
